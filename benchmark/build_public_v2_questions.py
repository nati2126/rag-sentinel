if __name__ == "__main__":
    with (ROOT / "questions" / "public_v2.jsonl").open("w", encoding="utf-8") as fh:
        for i, (g, cat, q, exp, stale, gold, dec, note) in enumerate(QUESTIONS, 1):
            row = {"id": f"R{i:02d}", "group": g, "category": cat, "question": q, "expected": exp, "stale": stale,
                   "gold_evidence": gold, "expected_decision": dec, "note": note}  # fmt: skip
            fh.write(json.dumps(row, ensure_ascii=False) + "\n")
    (ROOT / "conflicts" / "public_v2.json").write_text(
        "[\n" + ",\n".join("  " + json.dumps(c, ensure_ascii=False) for c in CONFLICTS) + "\n]\n", encoding="utf-8"
    )
    print(len(QUESTIONS), "questions,", len(CONFLICTS), "conflict pairs")
    print(Counter(q[1] for q in QUESTIONS), Counter(q[0] for q in QUESTIONS))
